"""Story text constraints are subordinate to the original visual reference rule."""
from reference_prompt_baseline import PROJECT13_REFERENCE_PROMPT

LAYOUT = '''【版式与裁切范围】
总画布1024×1536，2列×3行六宫格，左到右、上到下阅读，各格视觉等大。
仅画布最外圈4px和格间16px分隔条使用白色，内部为独立2px细黑矩形分镜框。
格内背景底色、纸面或其他材质、笔触、明暗、人物、道具、气泡与字体均依视觉母版；不得为满足白条把格内改成白底，不增加全格浅色底板。
人物、关键道具和完整文字容器留在本格内，距框内缘至少24px。白条与分镜框属于版式，不改变格内绘画媒介和视觉语言。
不加封面、独立标题栏、水印或跨格大图。'''

REFERENCE_PRIORITY = '''【视觉优先级与故事执行的边界】
上传参考图是唯一视觉母版，最高优先级。下方分镜只规定故事中谁做什么、说什么以及先后顺序，不另行指定美术风格。
所有格子的绘画媒介、底色与底材、轮廓形态、笔触颗粒、人物头身比例、脸型和五官画法、发型表现、配色规律、阴影、背景画法、喜剧夸张程度、气泡及旁白字体均强参考上传图，保持同一套视觉系统。
每个角色都采用参考图同一套人物画法，女性、妻子、母亲、女友和监考者同样受约束；不得只给男性沿用原画法，却把女性另画成美型动漫脸。参考图若是夸张或丑萌人物，保留其原有脸型、眼睛大小、鼻口和不精修的表情，不做美化。
参考图人物原有的露底和留白必须保留：原本未涂肤色的脸、手、脖子不得新增肉色或粉色填充，也不增加高光、美瞳、妆容、光滑皮肤或新的大色块。参考图本来有的色块和五官画法照原图继承。
无论脚本要求客厅、厨房、车站或其他事件，都使用参考图原有的画法表现；不得因此切换媒介、加入参考图没有的写实皮肤或普通动漫脸。
分镜中的角色身份只用于区分故事人物，未被原文明示的外观及服装依参考图合理适配，不按文本模型自行推定的美术外观改画。
对白气泡继承参考图气泡轮廓并保留所属人物指向；旁白独立无尾，不连接人物。旁白框的轮廓、位置与排布方式按下方【旁白样式与位置】从参考图读取，不预设统一形状或固定角落。无论采用何种旁白样式，媒介、笔触、底色、配色与字体均遵循参考图。
发生视觉冲突时以参考图为准。每格指定的文字仍须完整出现，放入与参考图协调的容器。'''

NARRATION_REFERENCE_RULE = '''【旁白样式与位置】
先按文字功能识别参考图中的旁白：旁白是叙述或动作、表情说明，不属于人物真正说出口的话，也不是手机、牌子等道具表面的字。不要把人物对白气泡或思考气泡误当作旁白样式。
参考图已经有旁白框、旁白底条或其他旁白容器时，继承其轮廓形态、是否描边、边缘笔触、填底或透明处理、文字颜色、字体、内边距与常用排布习惯。具体尺寸和位置随本格文字量与构图自然调整，保持参考图的视觉规律，不机械复制同一处坐标。
参考图没有可用的旁白样式时，依据该图已有的绘画媒介、线条、色彩范围、文字与容器语言，自行设计简洁协调的无尾旁白框；各格采用同一套衍生样式，不引入参考图之外的新配色、材质或字体。不默认套用矩形、白底黑字、统一色块或固定角落。
旁白框的位置结合本格人物、留白、阅读顺序和文字长度安排，可以放在适合的空处，不固定左上、上沿或下沿；不得遮住脸、手、关键动作和证据道具，不进入格间白条。
旁白始终不带指向人物的尾巴、人物连接线或思考小圆点，不表现为任何人物正在说话。即使参考图的叙述文字误放进有尾气泡，也只继承其视觉语言并取消人物指向，不延续归属错误。
对白与旁白通过人物指向和排布清楚区分，整张新图的文字容器仍属于参考图同一套画风。'''


def render_reference_plan(plan):
    from comic_prompt_planner import PANEL_COPY_RULE
    count = len(plan['panels'])
    layout = LAYOUT if count == 6 else LAYOUT.replace('2列×3行六宫格', '2列×2行四宫格')
    parts = [PROJECT13_REFERENCE_PROMPT, REFERENCE_PRIORITY, layout, NARRATION_REFERENCE_RULE,
             '【原文，仅供核对，不整段照印】\n' + plan['source_body'],
             '【故事场景与连续性，不另设画风】\n' + plan['scene'],
             '【故事人物身份，视觉画法全部依参考图】\n' + '\n'.join(plan['cast']),
             '【每格文字要求】\n' + PANEL_COPY_RULE,
             '【文字归属】\n下列对白、旁白、屏幕文字是唯一允许印出的正文。严格逐字采用给定字形，不得擅自简繁转换。动作说明、人物标签、格号、气泡数量均不印出。不同人物使用独立气泡，各句完整留在本格；旁白独立无尾，屏幕文字只在指定表面。容器外观和字体始终依参考图。']
    for i, panel in enumerate(plan['panels'], 1):
        dialogue = panel['dialogue']
        caption = panel['narration']
        lines = [f'第{i}格（第{(i-1)//2+1}行'+('左' if i % 2 else '右')+'）',
                 '画面动作（不印字）：' + panel['action'],
                 f'人物对白气泡数量：{len(dialogue)}。']
        for number, (who, text) in enumerate(dialogue, 1):
            lines.append(f'对白{number}（人物标签不印出；尾巴只指向{who}）：{text}')
        lines.append(f'独立无尾旁白容器数量：{int(bool(caption))}。样式与位置遵循【旁白样式与位置】，无人物指向、连接线或思考小圆点。')
        if caption:
            lines.append('旁白正文（叙述者文字，没有任何角色说出，不得画进有尾人物气泡）：' + caption)
        for where, text in panel.get('screens', []):
            lines.append(f'表面文字（仅印在{where}）：{text}')
        if not dialogue:
            lines.append('本格只有旁白，人物对白气泡为零。按参考图已有旁白样式放置独立无尾容器；参考图没有旁白时按其画风设计。形状与位置随本格构图和留白安排，文字不表现为人物正在说话。')
        parts.append('\n'.join(lines))
    parts.append('【最后核对】\n逐格至少有对白或旁白；文字无遗漏、不串格、不合并说话人、不把动作叙述变成角色自述。再与上传参考图核对媒介、底色、人物与线条、配色、气泡和字体，整张必须像同一套画风绘制。只输出一张完整宫格漫画。')
    return '\n\n'.join(parts) + '\n'
